# ─── Cover page ──────────────────────────────────────────────────────────────
def _draw_cover(c: pdfcanvas.Canvas, doc):
    w, h = PAGE_W, PAGE_H
    split = h * 0.6   # 50/50 split — dark top half, light bottom half

    # Bottom 70% — light
    c.setFillColor(LIGHT_BG)
    c.rect(0, 0, w, split, fill=1, stroke=0)

    # Top 30% — dark
    c.setFillColor(DARK)
    c.rect(0, split, w, h - split, fill=1, stroke=0)

    # Thin decorative rule at the split
    c.setFillColor(colors.HexColor("#475569"))
    c.rect(0, split - 0.5, w, 1, fill=1, stroke=0)

    # ── Dark section content (top 30%) ──
    # Brand label at very top
    c.setFillColor(TEXT_LIGHT)
    c.setFont("Helvetica", 8.5)
    c.drawString(2.5 * cm, h - 1.3 * cm, "THREATSHIELD  ·  SECURITY ASSESSMENT")

    # Thin rule under label
    c.setStrokeColor(colors.HexColor("#334155"))
    c.setLineWidth(0.5)
    c.line(2.5 * cm, h - 1.7 * cm, w - 2.5 * cm, h - 1.7 * cm)

    # Main title — single line
    c.setFillColor(WHITE)
    c.setFont("Helvetica-Bold", 22)
    c.drawString(2.5 * cm, split + 3.8 * cm, "Security Assessment Report")

    # Methodology label
    methodology = doc._ts_methodology or "STRIDE"
    c.setFillColor(colors.HexColor("#64748B"))
    c.setFont("Helvetica", 9.5)
    c.drawString(2.5 * cm, split + 2.8 * cm, f"Threat Modelling  ·  {methodology}")

    # ── Light section content (bottom 70%) ──
    project  = doc._ts_project or "Security Assessment"
    department      = doc._ts_department or ""
    gen_date = doc._ts_date or datetime.utcnow().strftime("%B %d, %Y")
    initiated_by = getattr(doc, "_ts_initiated_by", "") or ""

    # Project name — centred in the white section
    center_y = split / 2
    c.setFillColor(TEXT_MAIN)
    c.setFont("Helvetica-Bold", 18)
    max_chars = 52
    display_project = project if len(project) <= max_chars else project[:max_chars - 1] + "…"
    name_y = center_y + (0.5 * cm if department else 0)
    c.drawString(2.5 * cm, name_y, display_project)

    # Department — just below project name
    if department:
        c.setFillColor(TEXT_MID)
        c.setFont("Helvetica", 10.5)
        c.drawString(2.5 * cm, name_y - 0.8 * cm, department)

    # ── Meta info pinned to page bottom ──
    c.setFillColor(TEXT_MID)
    c.setFont("Helvetica", 9)
    # Build lines bottom-up: Classification → Prepared by → Date
    meta_lines = [f"Date   {gen_date}"]
    if initiated_by:
        meta_lines.append(f"Prepared by   {initiated_by}")
    meta_lines.append("Classification   Confidential — Internal Use Only")
    # Draw bottom rule above footer, then lines above it
    bottom_rule_y = 1.9 * cm
    c.setStrokeColor(RULE)
    c.setLineWidth(0.4)
    c.line(2.5 * cm, bottom_rule_y, w - 2.5 * cm, bottom_rule_y)
    meta_y = bottom_rule_y + 0.4 * cm
    for line in meta_lines:
        c.drawString(2.5 * cm, meta_y, line)
        meta_y += 0.5 * cm

    # Footer
    c.setFillColor(TEXT_LIGHT)
    c.setFont("Helvetica", 8)
    c.drawCentredString(w / 2, 1.2 * cm, "Generated by ThreatShield  ·  All findings are advisory recommendations")


