def _priority_style(st, score):
    try:
        s = float(score)
    except (TypeError, ValueError):
        return st["body_sm"]
    if s >= 7:  return st["priority_high"]
    if s >= 4:  return st["priority_med"]
    return st["priority_low"]


def _priority_label(score):
    try:
        s = float(score)
    except (TypeError, ValueError):
        return "Review"
    if s >= 7:  return "High Priority"
    if s >= 4:  return "Moderate Priority"
    return "Low Priority"


def _safe(val, fallback="—"):
    if val is None: return fallback
    if isinstance(val, (dict, list)): return json.dumps(val, indent=2)[:300]
    return str(val).strip() or fallback


def _wrap(text, w=85):
    if not text: return ""
    out = []
    for line in str(text).splitlines():
        out.extend(textwrap.wrap(line, w) or [""])
    return _html.escape("\n".join(out), quote=False)


# ─── Section divider ─────────────────────────────────────────────────────────
def _section_div(st, number: str, title: str):
    row = [[
        Paragraph(number, ParagraphStyle("SN", fontSize=8, textColor=TEXT_LIGHT,
            fontName="Helvetica-Bold", alignment=TA_CENTER)),
        Paragraph(title, ParagraphStyle("ST", fontSize=13, textColor=WHITE,
            fontName="Helvetica-Bold")),
    ]]
    usable_w = PAGE_W - 3.6 * cm  # matches inner_frame width
    t = Table(row, colWidths=[1.4 * cm, usable_w - 1.4 * cm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), DARK),
        ("VALIGN",     (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING",  (0, 0), (0, 0), 10),
        ("LEFTPADDING",  (1, 0), (1, 0), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING",   (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING",(0, 0), (-1, -1), 10),
        ("LINEBELOW",    (0, 0), (-1, -1), 1, colors.HexColor("#475569")),
    ]))
    return [Spacer(1, 0.3 * cm), t, Spacer(1, 0.5 * cm)]


